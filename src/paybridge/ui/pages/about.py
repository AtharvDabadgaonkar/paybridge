"""Module 10 - About PayBridge: scope, honesty statement and verified status."""
from __future__ import annotations

import json

import streamlit as st

from paybridge import __version__, config
from paybridge.copilot import client as llm_client
from paybridge.data.loader import load_manifest
from paybridge.program import program as P
from paybridge.ui import components as C
from paybridge.ui.services import model_bundle


def render() -> None:
    C.page_header(
        "About PayBridge",
        "What this project is, what is genuinely implemented, and what is explicitly out of scope.",
        eyebrow=f"Version {__version__}",
    )

    C.notice(
        "<b>Independent personal portfolio project.</b> PayBridge is not affiliated with, endorsed by "
        "or built for any employer, financial institution or payment processor. Every customer, "
        "payment, beneficiary and watchlist entry is fictional.",
        "synthetic", "⚠️",
    )

    st.markdown(
        """
### What PayBridge is

A simulation of a B2B cross-border payment operations platform with an explainable AI fraud engine
(**FraudLens**). It exists to demonstrate end-to-end product thinking: payment unit economics,
compliance operations, risk modelling, analyst workflow, programme delivery and product measurement —
built as working software rather than slideware.

### What is actually implemented

| Capability | Status |
| --- | --- |
| Reproducible synthetic dataset (seeded, regenerable) | Implemented |
| Rail pricing and unit economics engine with vectorised parity tests | Implemented |
| Payout state machine with lifecycle events and audit trail | Implemented |
| Executive analytics with live filtering | Implemented |
| KYB onboarding workflow, fictional-watchlist screening, reviewer decisions | Implemented (simulated) |
| FraudLens rules layer (14 configurable rules) | Implemented |
| FraudLens ML layer (3 candidates, chronological splits, tuned threshold) | Implemented |
| SHAP explanations with a deterministic fallback | Implemented |
| Investigation workbench with persisted decisions and audit trail | Implemented |
| Model evaluation: baseline vs ML vs combined at a matched operating point | Implemented |
| Grounded AI copilot with claim validation and no-API-key fallback | Implemented |
| Programme milestones, RAID, dependencies, release gates, shadow mode | Implemented |
| Product analytics and experiment design with computed sample sizes | Implemented |

### What is explicitly NOT implemented

- **No real money movement.** No provider, bank, wallet, chain or exchange is contacted. "Payouts" are
  rows in SQLite with an event history.
- **No real compliance.** Screening runs against a fictional list this project generates. No sanctions,
  PEP, adverse-media, identity or regulatory check is performed, and none of it is advice.
- **No realised savings.** Cost savings are counterfactual models under documented assumptions.
- **No validated usability claims.** The sub-five-minute onboarding goal is a target measured against
  simulated durations, never against moderated user testing.
- **No production model validation.** Metrics come from synthetic data generated by a known process;
  they are an optimistic upper bound, not a forecast of real-world performance.
- **No durable multi-user storage.** SQLite state lives in the container and is lost when the host
  recycles it.
"""
    )

    C.section("Live environment status", "Read from this running instance — nothing here is hardcoded.")
    manifest = load_manifest()
    bundle = model_bundle()
    qa = P.qa_summary()
    counts = manifest.get("row_counts", {})
    cards = [
        {"label": "Synthetic transactions", "value": C.fmt_int(counts.get("transactions", 0)),
         "sub": f"Seed {manifest.get('seed', '-')} · {manifest.get('window', {}).get('days', 0)}-day window",
         "tone": "navy"},
        {"label": "Businesses / events", "value": f"{counts.get('businesses', 0)} / {counts.get('product_events', 0):,}",
         "sub": f"{counts.get('compliance_cases', 0)} onboarding cases", "tone": "navy"},
        {"label": "Model", "value": bundle.model_name.replace("_", " ").title() if bundle else "Not trained",
         "sub": f"Threshold {bundle.threshold:.3f}" if bundle else "Rules layer only", "tone": "teal"},
        {"label": "AI copilot", "value": "LLM enabled" if llm_client.llm_available() else "Deterministic",
         "sub": "Anthropic key detected" if llm_client.llm_available() else "No API key — full fallback",
         "tone": "success" if llm_client.llm_available() else "teal"},
    ]
    C.kpi_cards(cards, columns=4)

    if qa.get("available"):
        failed = qa.get("failed", 0) + qa.get("errors", 0)
        C.notice(
            f"<b>Recorded test run:</b> {qa.get('passed', 0)} passed, {failed} failed/errored, "
            f"{qa.get('skipped', 0)} skipped of {qa.get('total', 0)} tests "
            f"(finished {qa.get('finished_at', '')[:19]}).",
            "success" if failed == 0 else "danger", "🧪",
        )
    else:
        C.notice(
            f"<b>No test run recorded in this environment.</b> {qa.get('reason', '')} "
            "Run <code>make test</code> locally to populate it. No test count is ever displayed that the "
            "suite did not actually produce.",
            "warning", "🧪",
        )

    with st.expander("Dataset manifest (assumptions and leakage controls)"):
        st.code(json.dumps(manifest, indent=2)[:6000], language="json")

    C.section("Architecture")
    st.markdown(
        """
```
app.py                     Streamlit shell and navigation
src/paybridge/
  config.py                corridors, rail economics, thresholds (single source of truth)
  data/                    seeded synthetic generator + cached loaders
  db/                      SQLite schema, audit log, seeds
  payments/                pricing engine, payout state machine
  compliance/              onboarding workflow, synthetic screening
  fraud/                   rules, features, model, SHAP, scoring, evaluation, investigations
  copilot/                 intents, deterministic analytics, evidence, validator, LLM client
  program/                 milestones, RAID, gates, shadow mode
  product/                 adoption metrics, experiment design
  analytics/               deterministic KPI layer shared by the UI and the copilot
  ui/                      theme, components, one module per page
```

Layering runs one way: `ui` → services → `data`/`db` → `config`. Pricing, rules, features and the
copilot validator contain no Streamlit code and are unit tested directly.
"""
    )

    C.section("Documentation")
    st.markdown(
        """
`docs/PRD.md` · `docs/PRODUCT_ROADMAP.md` · `docs/PROGRAM_PLAN.md` · `docs/ARCHITECTURE.md` ·
`docs/API_SPEC.md` · `docs/UNIT_ECONOMICS.md` · `docs/MODEL_CARD.md` · `docs/AI_SAFETY.md` ·
`docs/RESUME_CASE_STUDY.md`
"""
    )
    st.caption(f"Data directory: `{config.DATA_DIR}` · Model directory: `{config.MODEL_DIR}`")
    C.footer()
