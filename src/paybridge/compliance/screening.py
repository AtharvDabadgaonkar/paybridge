"""Synthetic watchlist screening simulation.

The watchlist is a FICTIONAL list generated by this project. Matching is a
simple normalised similarity score. This is a workflow demonstration, not a
sanctions-screening control, and must never be described as one.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from difflib import SequenceMatcher

import pandas as pd

DEFAULT_MATCH_THRESHOLD = 0.82

_SUFFIX_NOISE = re.compile(
    r"\b(inc|incorporated|llc|ltd|limited|co|corp|corporation|plc|gmbh|sa|bv|pte)\b\.?",
    re.IGNORECASE,
)


def normalise(name: str) -> str:
    cleaned = _SUFFIX_NOISE.sub(" ", str(name).lower())
    cleaned = re.sub(r"[^a-z0-9 ]+", " ", cleaned)
    return re.sub(r"\s+", " ", cleaned).strip()


def similarity(a: str, b: str) -> float:
    return SequenceMatcher(None, normalise(a), normalise(b)).ratio()


@dataclass(frozen=True)
class ScreeningHit:
    entry_id: str
    entity_name: str
    list_source: str
    entity_type: str
    country: str
    match_score: float
    is_fictional: bool = True

    def as_dict(self) -> dict:
        return {
            "entry_id": self.entry_id,
            "matched_entity": self.entity_name,
            "list_source": self.list_source,
            "entity_type": self.entity_type,
            "country": self.country,
            "match_score": round(self.match_score, 4),
            "is_fictional": self.is_fictional,
        }


def screen_entity(
    name: str,
    watchlist: pd.DataFrame,
    threshold: float = DEFAULT_MATCH_THRESHOLD,
    max_hits: int = 5,
) -> list[ScreeningHit]:
    """Score one entity name against the fictional watchlist."""
    if watchlist.empty or not str(name).strip():
        return []
    scored = [
        ScreeningHit(
            entry_id=str(row.entry_id),
            entity_name=str(row.entity_name),
            list_source=str(row.list_source),
            entity_type=str(row.entity_type),
            country=str(row.country),
            match_score=similarity(name, str(row.entity_name)),
        )
        for row in watchlist.itertuples()
    ]
    hits = [h for h in scored if h.match_score >= threshold]
    hits.sort(key=lambda h: h.match_score, reverse=True)
    return hits[:max_hits]


def classify_onboarding_risk(
    screening_hits: int,
    volume_tier: str,
    documents_complete: bool,
    ubo_complete: bool,
    high_risk_corridors: int = 0,
) -> tuple[str, list[str]]:
    """Deterministic onboarding risk classification with stated reasons."""
    reasons: list[str] = []
    score = 0
    if screening_hits >= 2:
        score += 3
        reasons.append(f"{screening_hits} potential watchlist matches require adjudication")
    elif screening_hits == 1:
        score += 2
        reasons.append("One potential watchlist match requires adjudication")
    if volume_tier == "enterprise":
        score += 1
        reasons.append("Enterprise declared volume tier")
    if not documents_complete:
        score += 2
        reasons.append("Incorporation or ownership documents incomplete")
    if not ubo_complete:
        score += 2
        reasons.append("Beneficial ownership checklist incomplete")
    if high_risk_corridors:
        score += 1
        reasons.append(f"{high_risk_corridors} elevated-risk destination corridor(s) declared")

    classification = "high" if score >= 4 else "medium" if score >= 2 else "low"
    if not reasons:
        reasons.append("No screening match, complete documentation and standard volume profile")
    return classification, reasons


def requires_manual_review(classification: str, screening_hits: int) -> bool:
    """Policy: anything above low risk, or any screening hit, needs a human."""
    return classification != "low" or screening_hits > 0
